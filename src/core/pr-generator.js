import { writeFileSync, existsSync } from 'fs';
import { join } from 'path';

export class PRGenerator {
  constructor(projectPath) {
    this.projectPath = projectPath;
  }

  generate(plan, changes, testResults) {
    const branchName = this.sanitizeBranchName(plan.request);
    const title = this.generateTitle(plan);
    const body = this.generateBody(plan, changes, testResults);
    const checklist = this.generateChecklist(testResults);
    const commits = this.generateCommits(changes);

    return {
      branch: branchName,
      title,
      body,
      checklist,
      commits,
      filesChanged: changes.changes?.map(c => ({
        file: c.file,
        action: c.action,
        additions: c.changes?.filter(p => p.added).reduce((sum, p) => sum + p.count, 0) || 0,
        deletions: c.changes?.filter(p => p.removed).reduce((sum, p) => sum + p.count, 0) || 0
      })) || []
    };
  }

  generateTitle(plan) {
    const request = (plan.request || 'update').trim();
    const maxLen = 72;
    if (request.length <= maxLen) return `feat: ${request}`;
    return `feat: ${request.substring(0, maxLen - 4)}...`;
  }

  generateBody(plan, changes, testResults) {
    const sections = [];

    // Summary
    sections.push('## Summary');
    sections.push(plan.explanation || 'No summary provided');
    sections.push('');

    // Changes
    sections.push('## Changes');
    if (changes.changes) {
      for (const change of changes.changes) {
        const icon = change.action === 'create' ? '✨' : '✏️';
        sections.push(`${icon} \`${change.file}\` - ${change.description}`);
      }
    }
    sections.push('');

    // Risks
    if (plan.risks && plan.risks.length > 0) {
      sections.push('## Risks & Considerations');
      for (const risk of plan.risks) {
        sections.push(`- ⚠️ ${risk}`);
      }
      sections.push('');
    }

    // Test Results
    if (testResults) {
      sections.push('## Test Results');
      sections.push(`- Tests: ${testResults.tests?.success ? '✅ Passed' : '❌ Failed'}`);
      sections.push(`- Lint: ${testResults.lint?.success ? '✅ Passed' : '❌ Failed'}`);
      sections.push('');
    }

    // Implementation Steps
    sections.push('## Implementation Steps');
    for (const step of plan.plan || []) {
      sections.push(`${step.step}. ${step.action}`);
    }
    sections.push('');

    // Checklist
    sections.push('## Checklist');
    sections.push('- [ ] Code follows project style guidelines');
    sections.push('- [ ] Tests added/updated');
    sections.push('- [ ] Documentation updated');
    sections.push('- [ ] No breaking changes');
    sections.push('- [ ] Self-review completed');

    return sections.join('\n');
  }

  generateChecklist(testResults) {
    return [
      { item: 'Tests pass', done: testResults?.tests?.success || false },
      { item: 'Lint passes', done: testResults?.lint?.success || false },
      { item: 'Types valid', done: false },
      { item: 'Build succeeds', done: false },
      { item: 'Documentation updated', done: false },
      { item: 'No console.logs', done: false },
      { item: 'No TODO comments', done: false }
    ];
  }

  generateCommits(changes) {
    const commits = [];
    const grouped = {};

    for (const change of changes.changes || []) {
      const type = change.action === 'create' ? 'feat' : 'fix';
      if (!grouped[type]) grouped[type] = [];
      grouped[type].push(change);
    }

    for (const [type, files] of Object.entries(grouped)) {
      commits.push({
        type,
        message: `${type}: ${files.map(f => f.file).join(', ')}`,
        files: files.map(f => f.file)
      });
    }

    return commits;
  }

  sanitizeBranchName(name) {
    return (name || 'devflow-update')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .substring(0, 50);
  }

  savePRDraft(prData, filename = 'PR_DRAFT.md') {
    const content = [
      `# ${prData.title}`,
      '',
      `**Branch:** \`${prData.branch}\``,
      '',
      prData.body,
      '',
      '---',
      '*Generated by DevFlow CLI*'
    ].join('\n');

    const filePath = join(this.projectPath, filename);
    writeFileSync(filePath, content);
    return filePath;
  }
}
